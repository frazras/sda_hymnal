#!/usr/bin/env python3
"""Build/check the pinned recording catalog and its Dart availability table.

tool/data/recording_sources.json is the reviewed source of truth. A plain run
copies it to the bundled catalog and regenerates the Dart availability table;
--check compares both offline without writing. --enumerate refreshes every
collection's files from the pinned Git tree and checks each directory against
the pinned source settings. It never downloads audio and never maps a file to
another book or medium: absent files become explicit gaps.
"""
import argparse
import json
from pathlib import Path
import re
import urllib.parse
import urllib.request

ROOT = Path(__file__).resolve().parents[1]
MANIFEST = 'tool/data/recording_sources.json'
ASSET = 'assets/hymnals/recordings.json'
DART = 'lib/services/recording_availability.dart'
# Medium -> (Dart RecordingKind, upstream settings field). Instrumental first.
MEDIA = {'instrumentalRecording': ('instrumental', 'InstrumentalMusicUrl'),
         'sungRecording': ('sung', 'SungMusicUrl')}


def encode(value):
    return json.dumps(value, ensure_ascii=False, indent=2) + '\n'


def _fetch_json(url):
    request = urllib.request.Request(url, headers={'Accept': 'application/vnd.github+json',
                                                   'User-Agent': 'sdahymnal-recording-catalog'})
    with urllib.request.urlopen(request, timeout=60) as response:
        return json.loads(response.read())


def enumerate_collections(manifest, tree, settings, root=ROOT):
    """Return a copy of manifest with items, totals and gaps taken from tree."""
    repository, revision = manifest['repository'], manifest['revision']
    if not re.fullmatch(r'[A-Za-z0-9_.-]+/[A-Za-z0-9_.-]+', repository) or not re.fullmatch(r'[0-9a-f]{40}', revision):
        raise ValueError('Recording sources must pin a repository and full commit')
    if tree.get('truncated') is not False or not isinstance(tree.get('tree'), list):
        raise ValueError('Need a complete recursive Git tree listing')
    blobs = {e['path']: e for e in tree['tree'] if e.get('type') == 'blob'}
    pinned = blobs.get(manifest['settingsPath'])
    if pinned is None or pinned['sha'] != manifest['settingsGitBlobSha1']:
        raise ValueError('Pinned source settings changed; review them before enumerating')
    owner, name = repository.split('/')
    by_id = {entry['Id']: entry for entry in settings}
    result = json.loads(json.dumps(manifest))
    seen = set()
    for collection in result['collections']:
        book, medium, directory = collection['bookId'], collection['medium'], collection['directory']
        if (book, medium) in seen or medium not in MEDIA:
            raise ValueError(f'Invalid or duplicate collection: {book} {medium}')
        seen.add((book, medium))
        template = by_id[collection['settingsId']][MEDIA[medium][1]]
        if template != f'https://{owner}.github.io/{name}/{urllib.parse.quote(directory)}/###.m4a':
            raise ValueError(f'Settings do not assign {directory} to {collection["settingsId"]}')
        pack = json.loads((root / f'assets/hymnals/{book}.json').read_text())
        if pack['book']['id'] != book:
            raise ValueError(f'Pack identity mismatch: {book}')
        items, missing, used = [], [], set()
        for identity in sorted((i['id'] for i in pack['items']), key=int):
            if not re.fullmatch(r'[1-9][0-9]{0,2}', identity):
                raise ValueError(f'Item {book}:{identity} has no three-digit source name')
            path = f'{directory}/{int(identity):03d}.m4a'
            blob = blobs.get(path)
            if blob is None:
                missing.append(identity)
                continue
            used.add(path)
            items.append(dict(itemId=identity, path=path, bytes=blob['size'], gitBlobSha1=blob['sha']))
        unmapped = sorted(p for p in blobs if p.startswith(directory + '/') and p not in used)
        if unmapped:
            raise ValueError(f'{len(unmapped)} source files have no {book} item, e.g. {unmapped[0]}')
        collection.update(expectedCount=len(items), totalBytes=sum(i['bytes'] for i in items),
                          missingItemIds=missing, items=items)
    return result


def ranges(numbers):
    spans = []
    for number in sorted(numbers):
        if spans and number == spans[-1][1] + 1:
            spans[-1][1] = number
        else:
            spans.append([number, number])
    return spans


def render_dart(catalog):
    table = {}
    for collection in catalog['collections']:
        kind = MEDIA[collection['medium']][0]
        numbers = [int(item['itemId']) for item in collection['items']]
        table.setdefault(collection['bookId'], {})[kind] = ranges(numbers)
    lines = [
        '// Generated by tool/build_recording_catalog.py from',
        f'// {ASSET}. Do not edit; regenerate after review.',
        "part of 'hymn_recordings.dart';",
        '',
        '/// Inclusive item-number ranges with a pinned recording, by exact book and',
        '/// kind. Lets availability checks stay synchronous; a test compares it with',
        '/// the bundled catalog so the two cannot drift.',
        'const recordingAvailability = <String, Map<RecordingKind, List<(int, int)>>>{',
    ]
    for book in sorted(table):
        lines.append(f"  '{book}': {{")
        for kind, _ in MEDIA.values():
            if kind not in table[book]:
                continue
            spans = [f'({a}, {b})' for a, b in table[book][kind]]
            single = f'    RecordingKind.{kind}: [{", ".join(spans)}],'
            if len(single) <= 80:
                lines.append(single)
            else:
                lines.append(f'    RecordingKind.{kind}: [')
                lines.extend(f'      {span},' for span in spans)
                lines.append('    ],')
        lines.append('  },')
    lines.append('};')
    return '\n'.join(lines) + '\n'


def outputs(manifest):
    return {ASSET: encode(manifest), DART: render_dart(manifest), MANIFEST: encode(manifest)}


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true', help='compare generated files without writing')
    parser.add_argument('--enumerate', action='store_true',
                        help='refresh files from the pinned Git tree (network unless --tree/--settings)')
    parser.add_argument('--tree', type=Path, help='saved GitHub git/trees?recursive=1 response')
    parser.add_argument('--settings', type=Path, help='saved settings.json at the pinned revision')
    args = parser.parse_args()
    manifest = json.loads((ROOT / MANIFEST).read_text())
    if args.enumerate:
        repository, revision = manifest['repository'], manifest['revision']
        tree = (json.loads(args.tree.read_text()) if args.tree else _fetch_json(
            f'https://api.github.com/repos/{repository}/git/trees/{revision}?recursive=1'))
        settings = (json.loads(args.settings.read_text()) if args.settings else _fetch_json(
            f'https://raw.githubusercontent.com/{repository}/{revision}/{manifest["settingsPath"]}'))
        manifest = enumerate_collections(manifest, tree, settings)
    stale = []
    for name, content in outputs(manifest).items():
        path = ROOT / name
        if args.check:
            if not path.exists() or path.read_text() != content:
                stale.append(name)
        elif not path.exists() or path.read_text() != content:
            path.write_text(content)
    if stale:
        raise SystemExit('Recording catalog differs from its sources: ' + ', '.join(stale))
    files = sum(len(c['items']) for c in manifest['collections'])
    gaps = sum(len(c['missingItemIds']) for c in manifest['collections'])
    print(f'Checked {len(manifest["collections"])} recording collections: {files} files, {gaps} gaps')
